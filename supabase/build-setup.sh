#!/usr/bin/env bash
# Regenerates setup-all.sql: every file in this folder concatenated in the
# README.md run order, for a one-paste setup in the Supabase SQL Editor.
# Run from anywhere:  bash supabase/build-setup.sh
set -euo pipefail
cd "$(dirname "$0")"

# leaderboards.sql is omitted on purpose: leaderboards-v2.sql drops and
# recreates both of its functions with a new return type, and running v1
# again afterwards fails with "cannot change return type".
ORDER=(
  00-base-schema profile-hardening guest-profile-trigger cosmetics avatars
  presence leaderboards-v2 leaderboards-alltime results-hardening room-results ranks
  profile-pages profile-activity profile-dossier badges badges-prestige
  friends friends-realtime friends-ping friends-recent invites invites-sent
  pulse polls daily-suspects username-suggestions
)

{
  cat <<'HEADER'
-- Open Mercy: complete database setup in ONE file.
-- Paste the whole file into the Supabase SQL Editor and press Run.
-- Generated by build-setup.sh from the files in this folder, in the order
-- listed in README.md. Do not edit this file; edit the source file and
-- regenerate. Every part is idempotent, so running it again is safe. If it
-- stops with an error, nothing is applied and the message names the
-- failing statement.
HEADER
  for f in "${ORDER[@]}"; do
    printf '\n-- =====================================================================\n'
    printf -- '-- %s.sql\n' "$f"
    printf -- '-- =====================================================================\n\n'
    tr -d '\r' < "$f.sql"
    printf '\n'
  done
  printf '\n-- Make the new tables and functions visible to the API right away.\n'
  printf "notify pgrst, 'reload schema';\n"
} > setup-all.sql

echo "wrote supabase/setup-all.sql ($(wc -l < setup-all.sql) lines)"
