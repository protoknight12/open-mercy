// Bundles game-server/src/browserHost.ts for the browser, so peer-hosted
// rooms run the same GameRoomDO code as the Cloudflare Worker. Runs before
// `vite` and `vite build` (predev / prebuild). Output is git-ignored.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const entry = resolve(here, '../../game-server/src/browserHost.ts')
const outfile = resolve(here, '../src/p2p/generated/roomHost.js')

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: '// GENERATED by frontend/scripts/build-room-host.mjs. Do not edit.' },
})
console.log('built', outfile)
